// Generates the commit-derived changelog shown by components/version-tag.tsx.
//
//   bun scripts/generate-changelog.ts
//
// Writes config/generated/changelog.ts (full release list, loaded lazily by the
// changelog dialog) and config/generated/latest.ts (just the newest release,
// imported eagerly for the header pill). Both files are gitignored.
//
// Never fails the build: without git or history it writes an empty changelog.
// On shallow clones (e.g. Vercel) it tries `git fetch --unshallow` first and
// otherwise generates from whatever history exists.
//
// Also writes config/generated/build-info.ts with `itemCacheKey`, a short hash
// of the source files that define the item data persisted in localStorage.
// The key only changes when those files change, so ordinary releases keep
// visitors' cached item data instead of refetching it.

import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { buildChangelog, type ChangelogEntry } from "../lib/changelog-core";

// Commits that start a new era and cut a major version. Add an abbreviated
// hash here (prefix match, so a short hash stays valid) plus a short era name.
const MAJOR_MILESTONES: Record<string, string> = {
  c2e7158: "Foundations", // initial Create Next App commit
  "62eda64": "Item selector overhaul", // searchable selector with tooltips
  "49769bc": "Recipe viewer", // recipes page debut
  "23330f1": "Localization", // i18n lands across the app
  ef2b2ff: "Ritual tracker", // browser-local ritual tracking
  "1d8a12d": "Stash scanning", // screenshot-based stash detection
};

// Files whose changes can alter the shape of the cached item data. Add a file
// here if it starts transforming items before they are cached.
const ITEM_CACHE_SOURCES = [
  "types/SimplifiedItem.ts",
  "hooks/use-tarkov-api.ts",
  "hooks/use-items-data.ts",
];

const root = path.resolve(import.meta.dirname, "..");
const outputDir = path.join(root, "config", "generated");

const log = (message: string) => console.log(`[changelog] ${message}`);
const warn = (message: string) => console.warn(`[changelog] ${message}`);

function git(args: string): string | null {
  try {
    return execSync(`git ${args}`, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      maxBuffer: 32 * 1024 * 1024,
    });
  } catch {
    return null;
  }
}

function isShallow(): boolean {
  return git("rev-parse --is-shallow-repository")?.trim() === "true";
}

function writeGenerated(entries: ChangelogEntry[]) {
  mkdirSync(outputDir, { recursive: true });
  const header = "// AUTO-GENERATED by scripts/generate-changelog.ts. Do not edit.\n\n";
  writeFileSync(
    path.join(outputDir, "changelog.ts"),
    `${header}import type { ChangelogEntry } from "@/lib/changelog-core";\n\nexport const changelog: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};\n`,
  );
  writeFileSync(
    path.join(outputDir, "latest.ts"),
    `${header}import type { ChangelogEntry } from "@/lib/changelog-core";\n\nexport const latestRelease: ChangelogEntry | null = ${JSON.stringify(entries[0] ?? null, null, 2)};\n`,
  );
  log(`wrote ${entries.length} releases to config/generated/`);
}

function writeBuildInfo() {
  const hash = createHash("sha256");
  for (const file of ITEM_CACHE_SOURCES) {
    hash.update(file);
    // Normalise line endings so Windows and Linux builds agree.
    hash.update(readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n"));
  }
  const itemCacheKey = hash.digest("hex").slice(0, 10);
  mkdirSync(outputDir, { recursive: true });
  writeFileSync(
    path.join(outputDir, "build-info.ts"),
    `// AUTO-GENERATED by scripts/generate-changelog.ts. Do not edit.\n\nexport const itemCacheKey = ${JSON.stringify(itemCacheKey)};\n`,
  );
  log(`item cache key ${itemCacheKey}`);
}

function main() {
  writeBuildInfo();

  if (!git("--version")) {
    warn("git is not available; writing an empty changelog");
    writeGenerated([]);
    return;
  }

  if (isShallow()) {
    git("fetch --unshallow --quiet");
    if (isShallow())
      warn("repository is still shallow; changelog will only cover fetched history");
  }

  const raw = git(
    'log --reverse --no-merges --shortstat --format="%x1e%h%x1f%aI%x1f%s%x1f%b%x1f"',
  );
  if (raw === null) {
    warn("git log failed; writing an empty changelog");
    writeGenerated([]);
    return;
  }

  writeGenerated(buildChangelog(raw, MAJOR_MILESTONES));
}

main();
